    const revHeadline = tInterval(withHoldout.map((s) => s.holdout!.revenueIncrementalPaise / 100));
    const medianRateWidth = median(withHoldout.map((s) => s.holdout!.ciHiPaise - s.holdout!.ciLoPaise));
    const medianRevWidth = median(withHoldout.map((s) => s.holdout!.revenueCiHiPaise - s.holdout!.revenueCiLoPaise));
    const perSeedTruth = withHoldout.map((s) => s.holdout!.trueIncrementalPaise / 100);
    const truthStat = tInterval(perSeedTruth);
    const widths = withHoldout.map((s) => (s.holdout!.ciHiPaise - s.holdout!.ciLoPaise) / 100);
    const example = withHoldout[0].holdout!;

    L.push("Randomization happens at `POLICY_CHECK`, **after** every gate has passed — only episodes");
    L.push("RecoverOS would genuinely have acted on enter the experiment. Episodes above ₹50,000 are");
    L.push("never held out.");
