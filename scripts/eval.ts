function parseArgs() {
  const args = process.argv.slice(2);
  const config: Record<string, string> = {};
  for (let i = 0; i < args.length; i++) {
    if (args[i].startsWith("--")) {
      const key = args[i].slice(2);
      config[key] = args[i + 1] ?? "true";
      i++;
    }
  }
  return {
    episodes: Number(config.episodes ?? 50_000),
    seeds: config.seeds ? config.seeds.split(",").map(Number) : Array.from({ length: 20 }, (_, i) => i + 1),
    holdout: Number(config.holdout ?? 5),
    resamples: Number(config.resamples ?? 10_000),
    sutva: (config.sutva ?? "1") !== "0",
    out: config.out ?? "",
    noWrite: "no-write" in config,
    force: "force" in config,
  };
}

const inr = (p: number) => Math.round(p / 100).toLocaleString("en-IN");
const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
const signedPct = (x: number) => `${x >= 0 ? "+" : ""}${(x * 100).toFixed(1)}%`;

const ARM_LABEL: Record<ArmKey, string> = {
  baseline: "Baseline (silent retry)",
  rules: "Rules",
  recoverOs: "**RecoverOS**",
  oracle: "Oracle (yardstick)",
};

function median(values: number[]): number {
  if (values.length === 0) return 0;
  const s = [...values].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
}

